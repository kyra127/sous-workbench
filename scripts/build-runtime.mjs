import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const projectDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sources = [
  "runtime-core.js",
  "workbench.js",
  "workbench-v2.js",
  "workbench-v4.js",
  "workbench-v6-pre.js",
  "workbench-v6.js",
  "workbench-v6-fixes.js",
  "workbench-v7.js",
  "workbench-v7-fixes.js",
  "workbench-v8-multigroup.js",
  "workbench-v9-feedback.js",
  "v26-final.js",
  "v27-final.js",
  "v28-final.js",
  "v29-consistency.js",
  "v30-entry.js",
  "v31-annotations.js",
  "v32-duplicate-guard.js",
];

const banner = [
  "/* SOUS unified browser runtime.",
  " * Generated by scripts/build-runtime.mjs.",
  " * Edit source modules, then run npm run build:runtime.",
  " */",
  "",
].join("\n");

const body = sources
  .map((file) => {
    const source = fs.readFileSync(path.join(projectDir, file), "utf8").trim();
    return `/* ===== ${file} ===== */\n${source}\n`;
  })
  .join("\n");

const output = `${banner}${body}`;
fs.writeFileSync(path.join(projectDir, "sous-runtime.js"), output, "utf8");
fs.writeFileSync(path.join(projectDir, "app.js"), output, "utf8");
console.log(`Built sous-runtime.js from ${sources.length} source modules.`);


